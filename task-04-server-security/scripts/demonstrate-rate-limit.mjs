import {
  checkIpRateLimit,
  recordIpFailedAttempt,
  createRateLimitResponse,
  extractClientIp,
  _clearRateLimitsForTesting
} from 'file:///C:/Users/gbola/Desktop/SchoolPass/src/lib/auth/rateLimit.ts';
import { writeFileSync } from 'node:fs';

_clearRateLimitsForTesting();

const log = [];
function print(msg = '') {
  console.log(msg);
  log.push(msg);
}

print('================================================================================');
print('SCHOOLPASS ASSESSMENT TASK 4: EVIDENCE 14');
print('RATE LIMIT TRIGGER AND GENUINE DEFEAT VIA CLIENT IP / INTERFACE CHANGE');
print('================================================================================');
print(`Timestamp: ${new Date().toISOString()}`);
print('Scope: auth_login / auth_register');
print('Rate Limit Threshold: 5 failed attempts per 15-minute sliding window');
print('Lockout Action: HTTP 429 Too Many Requests with Retry-After: 900');
print('IP Resolution: Verified Edge Header & Right-Most Proxy Anti-Spoofing Architecture');
print('');

// -----------------------------------------------------------------------------
// STEP 1: TRIGGER RATE LIMIT ON PRIMARY CLIENT IP (INTERFACE A)
// -----------------------------------------------------------------------------
const ipA = '192.168.1.105'; // Primary Ethernet/Wi-Fi Interface
print('--------------------------------------------------------------------------------');
print(`STEP 1: TRIGGERING RATE LIMIT ON PRIMARY CLIENT INTERFACE (${ipA})`);
print('--------------------------------------------------------------------------------');

for (let attempt = 1; attempt <= 5; attempt++) {
  const check = checkIpRateLimit(ipA, 'parent_auth');
  print(`Attempt ${attempt}/5: Checking rate limit for ${ipA}... Allowed: ${check.allowed} (Current attempts: ${check.attempts})`);
  
  const record = recordIpFailedAttempt(ipA, 'parent_auth');
  if (record.blocked) {
    print(`>> ATTEMPT ${attempt} FAILED: THRESHOLD EXCEEDED!`);
    print(`>> Lockout Applied: Blocked = true, Retry-After = ${record.retryAfterSeconds}s`);
  } else {
    print(`   Attempt ${attempt} failed: Recorded attempt ${record.attempts}. Remaining: ${5 - record.attempts}`);
  }
}

// Verify that subsequent attempt from IP A is blocked
print('');
print(`Testing 6th attempt from ${ipA}:`);
const checkBlocked = checkIpRateLimit(ipA, 'parent_auth');
print(`Check result: allowed = ${checkBlocked.allowed}, retryAfterSeconds = ${checkBlocked.retryAfterSeconds}`);

const response = createRateLimitResponse(checkBlocked.retryAfterSeconds);
print('HTTP Response Generated by Server:');
print(`  HTTP Status Code: ${response.status} (Too Many Requests)`);
print(`  Header Retry-After: ${response.headers.get('Retry-After')} seconds`);

const body = await response.json();
print(`  Response Body: ${JSON.stringify(body)}`);
print('Result: Lockout verified. IP A is strictly prohibited from further authentication attempts.');
print('');

// -----------------------------------------------------------------------------
// STEP 2: DEMONSTRATING THAT HEADER SPOOFING FAILS TO DEFEAT RATE LIMIT
// -----------------------------------------------------------------------------
print('--------------------------------------------------------------------------------');
print('STEP 2: ADVERSARIAL HEADER SPOOFING ATTEMPT (ANTI-SPOOFING VERIFICATION)');
print('--------------------------------------------------------------------------------');
print('An attacker attempts to bypass the lockout on IP A by injecting spoofed headers:');
print('  curl -H "X-Forwarded-For: 203.0.113.195, 192.168.1.105" ...');

const spoofedHeaders = {
  get: (name) => {
    if (name.toLowerCase() === 'x-forwarded-for') {
      return '203.0.113.195, 192.168.1.105'; // Attacker injected prefix; upstream proxy appended real IP
    }
    return null;
  }
};

const resolvedIp = extractClientIp(spoofedHeaders);
print(`Resolved Client IP via extractClientIp(): ${resolvedIp}`);

const spoofCheck = checkIpRateLimit(resolvedIp, 'parent_auth');
print(`Rate limit check for spoofed request: allowed = ${spoofCheck.allowed}, blocked = ${!spoofCheck.allowed}`);
print('Finding: SchoolPass anti-spoofing engine correctly selects the right-most trusted IP.');
print('The spoofed X-Forwarded-For header FAILS to bypass the lockout.');
print('');

// -----------------------------------------------------------------------------
// STEP 3: DEFEAT RATE LIMIT VIA LEGITIMATE NETWORK IDENTITY / INTERFACE CHANGE
// -----------------------------------------------------------------------------
const ipB = '197.210.64.82'; // Secondary Interface: Mobile Cellular Hotspot / Alternate Route
print('--------------------------------------------------------------------------------');
print(`STEP 3: DEFEATING RATE LIMIT VIA GENUINE CLIENT IP CHANGE (${ipB})`);
print('--------------------------------------------------------------------------------');
print('The user legitimately switches network connections (e.g., from Office Wi-Fi to Mobile Hotspot).');
print(`Client requests now originate from new physical IP: ${ipB}`);

const checkNewIp = checkIpRateLimit(ipB, 'parent_auth');
print(`Rate limit check for ${ipB}: allowed = ${checkNewIp.allowed}, attempts = ${checkNewIp.attempts}`);

if (checkNewIp.allowed) {
  print('>> REQUEST PERMITTED: Rate limit successfully defeated!');
  print('>> The server processes authentication normally for the new client IP.');
} else {
  print('>> Error: Request unexpectedly blocked.');
}
print('');

// -----------------------------------------------------------------------------
// STEP 4: CONCLUSION & ARCHITECTURAL SUMMARY
// -----------------------------------------------------------------------------
print('--------------------------------------------------------------------------------');
print('4. ARCHITECTURAL CONCLUSION & DEFENSE IN DEPTH');
print('--------------------------------------------------------------------------------');
print('1. IP-based rate limiting is a network-layer heuristic, NOT a complete identity control.');
print('2. Legitimate IP rotation (cellular network re-assignment, mobile tethering, or VPN change)');
print('   circumvents IP counters because the server cannot distinguish a rotating client from a new user.');
print('3. Defense-in-Depth Required for Serious Applications:');
print('   - Keying rate limits on Account Identity (e.g. parent email or phone number).');
print('   - Exponential backoff per account (regardless of source IP).');
print('   - Breached-password screening (HIBP k-anonymity) to neutralize credential stuffing.');
print('   - Cryptographic proof of work or behavioral CAPTCHA escalation on suspicious anomalies.');
print('================================================================================');

writeFileSync('task-04-server-security/evidence/14-rate-limit-defeated.txt', log.join('\n'));
print('Evidence saved to: task-04-server-security/evidence/14-rate-limit-defeated.txt');
